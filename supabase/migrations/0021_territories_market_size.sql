-- Live storage for Territories' market-size data (Skatteverket 'gron teknik'
-- install counts), replacing the bundled market-size-monthly.json / market-size.json
-- snapshot files -- Vercel's read-only/ephemeral filesystem means an in-app upload
-- feature can't write to those files, so this becomes the source of truth instead.
-- The trailing-12mo rollup (the old market-size.json shape) is now computed on read
-- (see src/lib/territories/marketSize.ts::readMarketSize()), not stored separately --
-- one table, no risk of the rollup and monthly detail drifting out of sync.
create table territories_market_size_monthly (
  province text not null,
  year int not null,
  month int not null,
  category text check (category in ('solar', 'battery', 'ev_charger')) not null,
  count int not null,
  primary key (province, year, month, category)
);

alter table territories_market_size_monthly enable row level security;
create policy "authenticated read/write" on territories_market_size_monthly for all to authenticated using (true) with check (true);

